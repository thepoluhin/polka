const { chromium } = require('playwright'); const fs = require('fs'), path = require('path');
(async () => {
  const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 1300, height: 860 } });
  const errs = []; page.on('pageerror', (e) => errs.push(e.message));
  await page.goto('file://' + path.resolve(__dirname, '../dist/app/index.html'));
  const d = fs.readFileSync(path.resolve(__dirname, '../testbooks/Северова - Дом у реки.fb2')).toString('base64');
  await page.evaluate(async (d) => { const bin = atob(d); const u = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) u[i] = bin.charCodeAt(i); await window.__polka.openEntry({ name: 'a.fb2', size: u.length, bytes: u, id: 'a' }); await window.__polka.goTo(1, { page: 0 }); }, d);
  await page.evaluate(() => window.__polka.changeSetting('cols', 'scroll')); await page.waitForTimeout(400);
  const st = () => page.evaluate(() => { const v = document.getElementById('viewport'); const R = window.__polka.R; return { ch: R.ch, off: R.off, top: Math.round(v.scrollTop), h: v.scrollHeight, status: document.getElementById('r-left').textContent, pct: document.getElementById('r-right').textContent }; });
  console.log('start', await st());
  await page.mouse.move(650, 400); await page.mouse.wheel(0, 1500); await page.waitForTimeout(500); console.log('wheel', await st());
  await page.keyboard.press('Space'); await page.waitForTimeout(700); console.log('space', await st());
  const off = (await st()).off;
  await page.evaluate(() => window.__polka.changeSetting('size', 24)); await page.waitForTimeout(500);
  const s2 = await st(); console.log('font 24, off kept:', off, s2.off);
  await page.keyboard.press('End'); await page.waitForTimeout(300);
  await page.screenshot({ path: process.argv[2] + '/60-scroll-end.png' });
  await page.keyboard.press('Space'); await page.waitForTimeout(800); console.log('next chapter', await st());
  await page.keyboard.press('ArrowUp'); await page.waitForTimeout(800); console.log('up at top -> prev chapter end', await st());
  await page.evaluate(() => window.__polka.changeSetting('size', 20));
  await page.keyboard.press('Home'); await page.waitForTimeout(300); await page.mouse.wheel(0, 900); await page.waitForTimeout(500);
  await page.mouse.move(650, 30); await page.waitForTimeout(300);
  await page.screenshot({ path: process.argv[2] + '/61-scroll.png' });
  const off3 = (await st()).off;
  await page.evaluate(() => window.__polka.changeSetting('cols', 'auto')); await page.waitForTimeout(600);
  console.log('back to pages, off kept:', off3, (await st()).off, await page.evaluate(() => [window.__polka.R.page, window.__polka.R.pages]));
  await page.screenshot({ path: process.argv[2] + '/62-paged.png' });
  console.log('errors', errs);
  await b.close();
})();
